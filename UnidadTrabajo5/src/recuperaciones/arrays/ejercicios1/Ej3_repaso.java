package recuperaciones.arrays.ejercicios1;

public class Ej3_repaso {

	public static void main(String[] args) {
		
		// Creamos un array de enteros
		int[] n = {5, 10, 15, 20, 25, 30, 35, 40, 45, 50};

		System.out.println("El primero: "+n[0]);
		System.out.println("El último: "+n[n.length-1]);
		System.out.println("El segundo: "+n[1]);
		System.out.println("El penúltimo: "+n[n.length-2]);
		System.out.println("El tercero: "+n[2]);
		System.out.println("El antepenúltimo: "+n[n.length-3]);
	}

}
