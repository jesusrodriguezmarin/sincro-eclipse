package ejemplos.figura;

public class Figura {

	// Atributo
	protected String color;

	/**
	 * Devuelve el color de la figura
	 * @return {String} el color de la figura
	 */
	public String getColor() {
		return color;
	}

	/**
	 * Establece el color de la figura
	 * @param color {String} el color a establecer
	 */
	public void setColor(String color) {
		this.color = color;
	}
	
	
}
